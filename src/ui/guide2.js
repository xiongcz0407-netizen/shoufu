const seen = (key) => !!(game.state.flags.hints && game.state.flags.hints[key]);
/** 晚一点出（等界面画好），同一个提示只出一次；屏幕上已经有一个提示，就等它关了再出 */
const pending = new Set();
export function hintLater(key, ms = 400) {
  if (seen(key) || pending.has(key)) return; pending.add(key);
  const go = () => { if (seen(key)) { pending.delete(key); return; } if (document.querySelector('.hint')) { setTimeout(go, 1500); return; } hint(key); pending.delete(key); };
  setTimeout(go, ms);
}
